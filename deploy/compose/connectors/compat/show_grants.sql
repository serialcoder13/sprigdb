DROP USER IF EXISTS r4c_u1, r4c_u2, r4c_u3;
DROP ROLE IF EXISTS r4c_r1, r4c_r2, r4c_r3;
DROP TABLE IF EXISTS c_g1;
DROP PROCEDURE IF EXISTS c_gp;
CREATE TABLE c_g1 (a INT, b INT, c INT);
CREATE PROCEDURE c_gp() SELECT 1;
CREATE USER r4c_u1 IDENTIFIED BY 'Sprig-dev-1!', r4c_u2 IDENTIFIED BY 'Sprig-dev-1!', r4c_u3 IDENTIFIED BY 'Sprig-dev-1!';
CREATE ROLE r4c_r1, r4c_r2, r4c_r3;
GRANT SELECT ON @DB@.* TO r4c_r1;
GRANT INSERT, UPDATE ON @DB@.c_g1 TO r4c_r2;
GRANT r4c_r3 TO r4c_r2;
GRANT DELETE ON @DB@.c_g1 TO r4c_r3;
GRANT SELECT (a, b), UPDATE (b) ON @DB@.c_g1 TO r4c_u1;
GRANT r4c_r1, r4c_r2 TO r4c_u1;
SET DEFAULT ROLE r4c_r1 TO r4c_u1;
GRANT ALL ON @DB@.* TO r4c_u2 WITH GRANT OPTION;
GRANT EXECUTE ON PROCEDURE @DB@.c_gp TO r4c_u2;
GRANT r4c_r1 TO r4c_u2 WITH ADMIN OPTION;
GRANT SELECT, INSERT, UPDATE, DELETE, CREATE, DROP, INDEX, ALTER ON *.* TO r4c_u3;
GRANT CREATE VIEW, SHOW VIEW, TRIGGER, EVENT, CREATE ROUTINE, ALTER ROUTINE, LOCK TABLES, REFERENCES, EXECUTE, CREATE TEMPORARY TABLES ON @DB@.* TO r4c_u3;
GRANT SELECT ON @DB@.c_g1 TO r4c_u3;
SHOW GRANTS FOR r4c_u1;
SHOW GRANTS FOR r4c_u1 USING r4c_r1, r4c_r2;
SHOW GRANTS FOR r4c_u2;
SHOW GRANTS FOR r4c_u3;
SHOW GRANTS FOR r4c_r1;
SHOW GRANTS FOR r4c_r2;
SHOW GRANTS FOR r4c_r2 USING r4c_r3;
REVOKE UPDATE (b) ON @DB@.c_g1 FROM r4c_u1;
REVOKE r4c_r2 FROM r4c_u1;
SHOW GRANTS FOR r4c_u1;
REVOKE INSERT ON @DB@.* FROM r4c_u3;
REVOKE INSERT ON @DB@.c_g1 FROM r4c_u3;
REVOKE SELECT, INSERT ON @DB@.* FROM r4c_u2;
SHOW GRANTS FOR r4c_u2;
SHOW GRANTS FOR r4c_nosuchuser;
