//! The Helm chart's `crds/` are the generated CRDs (chapter 27 step 11).
//! `SPRIG_OPERATOR_REGEN=1` rewrites them. Helm isn't run here: the
//! templates get only structural checks.

#![allow(clippy::unwrap_used)]

use std::path::PathBuf;

use sprig_operator::{crd, yaml};

fn chart() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../../charts/sprigdb")
}

#[test]
fn checked_in_crds_are_current() {
    let dir = chart().join("crds");
    let regen = std::env::var_os("SPRIG_OPERATOR_REGEN").is_some();
    let mut stale = Vec::new();
    for c in crd::crds() {
        let name = format!("{}.yaml", c["metadata"]["name"].as_str().unwrap());
        let text = format!(
            "# Generated by sprig-operator (crd::crds). Do not edit: run\n\
             # SPRIG_OPERATOR_REGEN=1 cargo test -p sprig-operator --test chart\n{}",
            yaml::to_yaml(&c)
        );
        let path = dir.join(&name);
        if regen {
            std::fs::create_dir_all(&dir).unwrap();
            std::fs::write(&path, &text).unwrap();
        } else if std::fs::read_to_string(&path).ok().as_deref() != Some(text.as_str()) {
            stale.push(name);
        }
    }
    assert!(
        stale.is_empty(),
        "charts/sprigdb/crds is stale for {stale:?}"
    );
}

#[test]
fn templates_are_balanced_and_the_chart_lists_every_role() {
    let t = chart().join("templates");
    let mut names: Vec<String> = std::fs::read_dir(&t)
        .unwrap()
        .map(|e| e.unwrap().file_name().to_string_lossy().into_owned())
        .collect();
    names.sort();
    for want in [
        "configmap-toml.yaml",
        "etcd-dc.yaml",
        "etcd-global.yaml",
        "controller.yaml",
        "gateway.yaml",
        "worker.yaml",
        "operator.yaml",
        "certificates.yaml",
        "settings-job.yaml",
        "pools.yaml",
        "pdb.yaml",
        "networkpolicy.yaml",
        "servicemonitor.yaml",
    ] {
        assert!(names.iter().any(|n| n == want), "missing {want}");
    }
    for n in &names {
        let s = std::fs::read_to_string(t.join(n)).unwrap();
        // Every action closes before the next one opens (YAML flow maps
        // also end in "}}", so counting alone would mislead).
        let mut rest = s.as_str();
        while let Some(i) = rest.find("{{") {
            let after = &rest[i + 2..];
            let close = after
                .find("}}")
                .unwrap_or_else(|| panic!("{n}: unclosed {{{{"));
            assert!(
                after.find("{{").is_none_or(|j| j > close),
                "{n}: an action opens inside another"
            );
            rest = &after[close + 2..];
        }
        assert!(!s.contains('\t'), "{n}: tabs in YAML");
        let opens = s.matches("{{- if").count()
            + s.matches("{{ if").count()
            + s.matches("{{- range").count()
            + s.matches("{{ range").count()
            + s.matches("{{- with").count()
            + s.matches("{{ with").count()
            + s.matches("{{- define").count();
        let ends = s.matches("{{- end").count() + s.matches("{{ end").count();
        assert_eq!(opens, ends, "{n}: if/range/with/define without end");
    }
    let values = std::fs::read_to_string(chart().join("values.yaml")).unwrap();
    let schema: serde_json::Value =
        serde_json::from_str(&std::fs::read_to_string(chart().join("values.schema.json")).unwrap())
            .unwrap();
    for key in schema["properties"].as_object().unwrap().keys() {
        assert!(
            values.lines().any(|l| l.starts_with(&format!("{key}:"))),
            "values.yaml lacks {key}"
        );
    }
}
