//! The Helm chart's `crds/` are the generated CRDs (chapter 27 step 11).
//! `SPRIG_OPERATOR_REGEN=1` rewrites them. Helm isn't run here: the
//! templates get only structural checks.

#![allow(clippy::unwrap_used)]

use std::path::PathBuf;

use sprig_operator::{crd, yaml};

fn chart() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../../charts/sprigdb")
}

#[test]
fn checked_in_crds_are_current() {
    let dir = chart().join("crds");
    let regen = std::env::var_os("SPRIG_OPERATOR_REGEN").is_some();
    let mut stale = Vec::new();
    for c in crd::crds() {
        let name = format!("{}.yaml", c["metadata"]["name"].as_str().unwrap());
        let text = format!(
            "# Generated by sprig-operator (crd::crds). Do not edit: run\n\
             # SPRIG_OPERATOR_REGEN=1 cargo test -p sprig-operator --test chart\n{}",
            yaml::to_yaml(&c)
        );
        let path = dir.join(&name);
        if regen {
            std::fs::create_dir_all(&dir).unwrap();
            std::fs::write(&path, &text).unwrap();
        } else if std::fs::read_to_string(&path).ok().as_deref() != Some(text.as_str()) {
            stale.push(name);
        }
    }
    assert!(
        stale.is_empty(),
        "charts/sprigdb/crds is stale for {stale:?}"
    );
}

#[test]
fn templates_are_balanced_and_the_chart_lists_every_role() {
    let t = chart().join("templates");
    let mut names: Vec<String> = std::fs::read_dir(&t)
        .unwrap()
        .map(|e| e.unwrap().file_name().to_string_lossy().into_owned())
        .collect();
    names.sort();
    for want in [
        "configmap-toml.yaml",
        "etcd-dc.yaml",
        "etcd-global.yaml",
        "controller.yaml",
        "gateway.yaml",
        "worker.yaml",
        "operator.yaml",
        "certificates.yaml",
        "settings-job.yaml",
        "pools.yaml",
        "pdb.yaml",
        "networkpolicy.yaml",
        "servicemonitor.yaml",
    ] {
        assert!(names.iter().any(|n| n == want), "missing {want}");
    }
    for n in &names {
        let s = std::fs::read_to_string(t.join(n)).unwrap();
        // Every action closes before the next one opens (YAML flow maps
        // also end in "}}", so counting alone would mislead).
        let mut rest = s.as_str();
        while let Some(i) = rest.find("{{") {
            let after = &rest[i + 2..];
            let close = after
                .find("}}")
                .unwrap_or_else(|| panic!("{n}: unclosed {{{{"));
            assert!(
                after.find("{{").is_none_or(|j| j > close),
                "{n}: an action opens inside another"
            );
            rest = &after[close + 2..];
        }
        assert!(!s.contains('\t'), "{n}: tabs in YAML");
        let opens = s.matches("{{- if").count()
            + s.matches("{{ if").count()
            + s.matches("{{- range").count()
            + s.matches("{{ range").count()
            + s.matches("{{- with").count()
            + s.matches("{{ with").count()
            + s.matches("{{- define").count();
        let ends = s.matches("{{- end").count() + s.matches("{{ end").count();
        assert_eq!(opens, ends, "{n}: if/range/with/define without end");
    }
    let values = std::fs::read_to_string(chart().join("values.yaml")).unwrap();
    let schema: serde_json::Value =
        serde_json::from_str(&std::fs::read_to_string(chart().join("values.schema.json")).unwrap())
            .unwrap();
    for key in schema["properties"].as_object().unwrap().keys() {
        assert!(
            values.lines().any(|l| l.starts_with(&format!("{key}:"))),
            "values.yaml lacks {key}"
        );
    }
}

fn template(name: &str) -> String {
    std::fs::read_to_string(chart().join("templates").join(name)).unwrap()
}

/// The comma list a `define` in `_helpers.tpl` returns.
fn helper_list(name: &str) -> Vec<String> {
    let h = template("_helpers.tpl");
    let start = format!("{{{{- define \"{name}\" -}}}}\n");
    let i = h.find(&start).unwrap_or_else(|| panic!("no {name}")) + start.len();
    let line = h[i..].lines().next().unwrap();
    line.split(',').map(str::to_owned).collect()
}

/// Where the template block opened at `open` (`{{- if`, `range` or
/// `with`) ends: the index of its matching `{{- end }}`.
fn block_end(t: &str, open: usize) -> usize {
    let mut depth = 0_i32;
    let mut i = open;
    while let Some(off) = t[i..].find("{{") {
        let at = i + off;
        let body = t[at + 2..].trim_start_matches('-').trim_start();
        if ["if ", "range ", "with ", "define "]
            .iter()
            .any(|k| body.starts_with(k))
        {
            depth += 1;
        } else if body.starts_with("end") {
            depth -= 1;
            if depth == 0 {
                return at;
            }
        }
        i = at + 2;
    }
    panic!("unbalanced block at {open}");
}

#[test]
fn client_certificates_are_set_on_every_listener_with_the_gateways_keys() {
    let all = helper_list("sprigdb.allListeners");
    // The gateway registers exactly these listeners' client_cert keys and
    // the CA path the settings job writes.
    let gw = std::fs::read_to_string(
        PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../sprig-gateway/src/listener/settings.rs"),
    )
    .unwrap();
    let registered: Vec<String> = gw
        .lines()
        .filter_map(|l| l.strip_prefix("client_cert!(\""))
        .map(|l| l.split('"').next().unwrap().to_owned())
        .collect();
    assert_eq!(
        all, registered,
        "sprigdb.allListeners vs the gateway's listeners"
    );
    assert!(gw.contains("\"tls.bundles.default.client_ca_path\""));
    for plain in helper_list("sprigdb.plainListeners") {
        assert!(all.contains(&plain), "{plain}");
    }
    for opt in helper_list("sprigdb.optionalListeners") {
        assert!(all.contains(&opt), "{opt}");
    }

    let job = template("settings-job.yaml");
    assert!(job.contains(
        "settings set listener.{{ $name }}.client_cert {{ include \"sprigdb.clientCert\" (dict \"root\" $ \"name\" $name) }}"
    ));
    assert!(job.contains("range $name := splitList \",\" (include \"sprigdb.allListeners\" .)"));
    assert!(job.contains("settings set tls.bundles.default.client_ca_path \"{{ $caPath }}\""));
    // The CA is set before any listener asks for client certificates, and
    // asking without a CA doesn't render.
    let ca = job.find("tls.bundles.default.client_ca_path").unwrap();
    let modes = job.find(".client_cert {{").unwrap();
    assert!(ca < modes, "client_ca_path must be set before client_cert");
    assert!(job.contains("{{- if and (include \"sprigdb.anyClientCert\" .) (not $caPath) }}"));
    assert!(job.contains("{{- fail \"gateway.clientTls.clientCert asks for client certificates"));
    // The CA path and every mode are written only inside `if $caPath`, so
    // without gateway.clientTls.clientCa an upgrade leaves values set by
    // hand at the DC's scope alone (authfix2).
    let open = job.find("{{- if $caPath }}").expect("if $caPath");
    let close = block_end(&job, open);
    assert!(open < ca && ca < close, "client_ca_path outside if $caPath");
    assert!(
        open < modes && modes < close,
        "client_cert outside if $caPath"
    );
    assert_eq!(job.matches(".client_cert {{").count(), 1);

    let gw_t = template("gateway.yaml");
    assert!(
        gw_t.contains(
            "- name: client-ca\n          secret: {secretName: {{ $clientCa.secretName }}}"
        )
    );
    assert!(
        gw_t.contains("- name: client-ca\n          configMap: {name: {{ $clientCa.configMap }}}")
    );
    assert!(gw_t.contains("- {name: client-ca, mountPath: {{ $clientCa.mountPath | default \"/etc/sprigdb/client-ca\" }}, readOnly: true}"));
    let helpers = template("_helpers.tpl");
    assert!(helpers.contains(
        "{{ $ca.mountPath | default \"/etc/sprigdb/client-ca\" }}/{{ $ca.key | default \"ca.crt\" }}"
    ));

    // values.schema.json: one entry per listener, and the gateway's modes.
    let schema: serde_json::Value =
        serde_json::from_str(&std::fs::read_to_string(chart().join("values.schema.json")).unwrap())
            .unwrap();
    let cc = &schema["properties"]["gateway"]["properties"]["clientTls"]["properties"];
    let mut listed: Vec<String> = cc["clientCert"]["properties"]["listeners"]["properties"]
        .as_object()
        .unwrap()
        .keys()
        .cloned()
        .collect();
    listed.sort();
    let mut want = all.clone();
    want.sort();
    assert_eq!(listed, want);
    assert_eq!(
        schema["$defs"]["clientCertMode"]["anyOf"][0]["enum"],
        serde_json::json!(["off", "optional", "required"])
    );
    for k in ["secretName", "configMap", "key", "mountPath"] {
        assert!(cc["clientCa"]["properties"][k].is_object(), "clientCa.{k}");
    }
    let values = std::fs::read_to_string(chart().join("values.yaml")).unwrap();
    assert!(values.contains("    clientCert:\n      default: \"off\"\n      listeners: {}\n"));
    assert!(values.contains("    clientCa: {secretName: \"\", configMap: \"\", key: ca.crt, mountPath: /etc/sprigdb/client-ca}\n"));
}

#[test]
fn controllers_register_an_admin_address_kubernetes_resolves() {
    let c = template("controller.yaml");
    assert!(c.contains("kind: StatefulSet\nmetadata:\n  name: sprigdb-controller\n"));
    assert!(c.contains("  serviceName: sprigdb-controller-pods\n"));
    // The headless Service that gives each pod its name.
    let svc = c
        .split("\n---\n")
        .find(|d| d.contains("name: sprigdb-controller-pods\n") && d.contains("kind: Service"))
        .expect("the headless Service");
    assert!(svc.contains("clusterIP: None"));
    assert!(svc.contains("publishNotReadyAddresses: true"));
    assert!(svc.contains("{name: admin, port: 7480}"));
    // The advertised address, as the controller reads it.
    let line = c
        .lines()
        .find(|l| l.contains("name: SPRIGDB_CONTROLLER_ADMIN_ADVERTISE"))
        .expect("SPRIGDB_CONTROLLER_ADMIN_ADVERTISE");
    let value = line
        .split("value: \"")
        .nth(1)
        .unwrap()
        .trim_end_matches("\"}");
    assert_eq!(
        value,
        "$(POD_NAME).sprigdb-controller-pods.{{ .Release.Namespace }}.svc:7480"
    );
    assert!(c.contains(
        "- name: POD_NAME\n              valueFrom: {fieldRef: {fieldPath: metadata.name}}"
    ));
    let pod = value
        .replace("$(POD_NAME)", "sprigdb-controller-1")
        .replace("{{ .Release.Namespace }}", "sprigdb");
    // The rest as configmap-toml.yaml writes it, trimmed.
    let cfg = sprig_common::ProcessConfig::from_toml_and_env(
        "[node]\ndc = \"fra1\"\n[controller]\nadmin_addr = \"0.0.0.0:7480\"\n",
        [("SPRIGDB_CONTROLLER_ADMIN_ADVERTISE".to_owned(), pod.clone())],
    )
    .unwrap();
    assert_eq!(
        cfg.controller.admin_advertise.as_deref(),
        Some(pod.as_str())
    );
    // The Admin API's certificate covers it (one DNS label under the
    // wildcard).
    let certs = template("certificates.yaml");
    assert!(certs.contains("- \"*.sprigdb-controller-pods.{{ $.Release.Namespace }}.svc\""));
    let values = std::fs::read_to_string(chart().join("values.yaml")).unwrap();
    assert!(values.contains("*.sprigdb-controller-pods.<namespace>.svc"));
}

#[test]
fn every_role_with_telemetry_has_a_service_the_service_monitor_scrapes() {
    let t = chart().join("templates");
    let mut docs = Vec::new();
    for e in std::fs::read_dir(&t).unwrap() {
        let s = std::fs::read_to_string(e.unwrap().path()).unwrap();
        docs.extend(s.split("\n---\n").map(str::to_owned).collect::<Vec<_>>());
    }
    let component = |d: &str, key: &str| -> Option<String> {
        let i = d.find(key)? + key.len();
        Some(d[i..].split('}').next()?.trim().to_owned())
    };
    let mut roles = Vec::new();
    for d in &docs {
        if d.contains("containerPort: 9180}") && d.contains("name: telemetry, containerPort") {
            roles.push(component(d, "matchLabels: {app.kubernetes.io/component:").unwrap());
        }
    }
    roles.sort();
    assert_eq!(roles, ["controller", "gateway", "operator", "worker"]);
    for r in &roles {
        let n = docs
            .iter()
            .filter(|d| {
                d.contains("kind: Service\n")
                    && component(d, "selector: {app.kubernetes.io/component:").as_deref()
                        == Some(r.as_str())
                    && d.contains("{name: telemetry, port: 9180}")
            })
            .count();
        // Exactly one, or Prometheus scrapes each pod twice.
        assert_eq!(n, 1, "{r}: Services publishing telemetry");
    }
    // The leading operator reads mariadb-operator's backup Jobs.
    assert!(
        template("operator.yaml")
            .contains("  - apiGroups: [batch]\n    resources: [jobs]\n    verbs: [list]\n")
    );
}

/// Every pod the chart runs carries the chart's labels: the network policies
/// admit only pods with `app.kubernetes.io/name: sprigdb` to the Admin and
/// etcd ports. The settings Job had none, so on a cluster that enforces
/// network policies it never reached the controllers (found on kind).
#[test]
fn every_pod_template_carries_the_chart_labels() {
    let t = chart().join("templates");
    let mut checked = 0;
    for e in std::fs::read_dir(&t).unwrap() {
        let path = e.unwrap().path();
        let s = std::fs::read_to_string(&path).unwrap();
        for doc in s.split("\n---\n") {
            // The innermost pod template: after the last `template:` line.
            let Some(i) = doc.rfind("template:\n") else {
                continue;
            };
            if !(doc.contains("kind: Deployment")
                || doc.contains("kind: StatefulSet")
                || doc.contains("kind: Job")
                || doc.contains("kind: CronJob"))
            {
                continue;
            }
            let pod = &doc[i..];
            let spec = pod.find("spec:").unwrap();
            assert!(
                pod[..spec].contains("include \"sprigdb.labels\""),
                "{}: a pod template without the chart's labels",
                path.display()
            );
            checked += 1;
        }
    }
    // controller, gateway, worker, operator, etcd-dc, etcd-global, the
    // settings Job and the defrag CronJob.
    assert_eq!(checked, 8);
}

/// The settings Job's calls only the DC leader serves are sent again to
/// the leader's own name when the controller Service lands on another
/// controller (39504); before, with two or more controllers the Job failed
/// until every call happened to land on the leader (found on kind).
#[test]
fn the_settings_job_follows_the_leader() {
    let job = template("settings-job.yaml");
    assert!(job.contains("ctl() {"));
    assert!(job.contains("send the request to the leader, \\([A-Za-z0-9._-]*\\)"));
    assert!(
        job.contains(
            "://$leader.sprigdb-controller-pods.{{ .Release.Namespace }}.svc:7480\" \"$@\""
        )
    );
    assert!(template("controller.yaml").contains("  serviceName: sprigdb-controller-pods\n"));
    // Every Admin call goes through ctl.
    assert_eq!(
        job.matches("sprigctl --endpoint").count(),
        2,
        "only inside ctl"
    );
    for l in job.lines().filter(|l| l.contains(" settings set ")) {
        assert!(l.trim_start().starts_with("ctl settings set "), "{l}");
    }
    // dc register's tags: key=value pairs joined by commas, none trailing
    // (sprigctl refuses an empty tag), and no --tags without tags.
    assert!(job.contains("{{ if $tags }} --tags {{ join \",\" $tags | squote }}{{ end }}"));
}

/// The operator's cluster registration follows the DC leader as the
/// settings Job does: its leader-address template names the controller's
/// own name under the headless Service, with the Admin API's scheme.
#[test]
fn the_operator_registers_through_the_leader() {
    let op = template("operator.yaml");
    assert!(op.contains(
        "{name: SPRIG_OPERATOR_CONTROLLER_LEADER_ADMIN, value: \"{{ include \"sprigdb.adminScheme\" . }}://{leader}.sprigdb-controller-pods.{{ .Release.Namespace }}.svc:7480\"}"
    ));
    let cfg = sprig_operator::OperatorConfig::from_env("ns", &|k| {
        (k == "SPRIG_OPERATOR_CONTROLLER_LEADER_ADMIN")
            .then(|| "https://{leader}.sprigdb-controller-pods.ns.svc:7480".to_owned())
    });
    assert_eq!(
        cfg.controller_leader_admin.as_deref(),
        Some("https://{leader}.sprigdb-controller-pods.ns.svc:7480")
    );
}

/// Gateways register `<pod IP, dashed>.sprigdb-gateway-pods.<ns>.svc`,
/// which the headless Service resolves and the gateway certificate
/// covers. Before, a gateway registered its hostname, which nothing else
/// in Kubernetes resolves: Kafka's metadata named it, and other gateways
/// and the workers couldn't reach its peer service (found on kind).
#[test]
fn gateways_register_an_address_kubernetes_resolves() {
    let g = template("gateway.yaml");
    let svc = g
        .split("\n---\n")
        .find(|d| d.contains("name: sprigdb-gateway-pods\n") && d.contains("kind: Service"))
        .expect("the headless Service");
    assert!(svc.contains("clusterIP: None"));
    assert!(svc.contains("publishNotReadyAddresses: true"));
    assert!(svc.contains("selector: {app.kubernetes.io/component: gateway}"));
    assert!(
        !svc.contains("9180"),
        "telemetry is sprigdb-gateway-health's"
    );
    let line = g
        .lines()
        .find(|l| l.contains("export SPRIGDB_GATEWAY_ADVERTISE_ADDR="))
        .expect("the advertised address");
    assert!(line.contains(
        "\"$(printf '%s' \"$POD_IP\" | tr '.:' '--').sprigdb-gateway-pods.{{ .Release.Namespace }}.svc\""
    ));
    assert!(g.contains("exec /usr/bin/sprigdb gateway --config /etc/sprigdb/config/sprigdb.toml"));
    assert!(g.contains(
        "- name: POD_IP\n              valueFrom: {fieldRef: {fieldPath: status.podIP}}"
    ));
    // The gateway reads it as [gateway] advertise_addr.
    let addr = "10-244-0-7.sprigdb-gateway-pods.sprigdb.svc";
    let cfg = sprig_common::ProcessConfig::from_toml_and_env(
        "[node]\ndc = \"fra1\"\n",
        [("SPRIGDB_GATEWAY_ADVERTISE_ADDR".to_owned(), addr.to_owned())],
    )
    .unwrap();
    assert_eq!(cfg.gateway.advertise_addr.as_deref(), Some(addr));
    assert!(
        template("certificates.yaml")
            .contains("- \"*.sprigdb-gateway-pods.{{ $.Release.Namespace }}.svc\"")
    );
}

/// With TLS, the per-user backend connections check MariaDB's certificate
/// against the CA bundle the gateways mount; without `ca_file` they used
/// the public roots and every login failed with `UnknownIssuer` (found on
/// kind). A secret made by an older chart gets the line on upgrade.
#[test]
fn backend_connections_check_mariadb_against_the_ca_bundle() {
    let b = template("gateway-backends.yaml");
    assert!(b.contains("{{- $ca := \"/etc/sprigdb/ca/ca.crt\" }}"));
    assert!(b.contains("tls = \\\"verify\\\"\\nca_file = \\\"%s\\\"\\n"));
    assert!(b.contains("(not (contains \"ca_file\" $text))"));
    // The bundle is mounted there on the gateways when TLS is on.
    let helpers = template("_helpers.tpl");
    assert!(helpers.contains("- {name: ca-bundle, mountPath: /etc/sprigdb/ca, readOnly: true}"));
    assert!(
        template("gateway.yaml").contains("{{- include \"sprigdb.tlsMounts\" . | nindent 12 }}")
    );
}
