//! systemd units and `mariadb.service` drop-ins for VMs (chapter 27, "VM
//! packaging"). The packages install [`units`] under
//! `/usr/lib/systemd/system/`; `deploy/vm/systemd/` holds the same files,
//! generated here (a test keeps them equal).

use std::fmt::Write as _;

/// A SprigDB unit.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Unit {
    /// `sprigdb-gateway`.
    Gateway,
    /// `sprigdb-controller`.
    Controller,
    /// `sprigdb-worker`.
    Worker,
    /// `sprigdb-agent`: runs as root on database hosts and starts MariaDB.
    Agent,
    /// `sprigdb-etcd-dc`: a member of the DC tier.
    EtcdDc,
    /// `sprigdb-etcd-global`: a global voter.
    EtcdGlobal,
}

impl Unit {
    /// Every unit, in the order the packages list them.
    pub const ALL: [Unit; 6] = [
        Unit::Gateway,
        Unit::Controller,
        Unit::Worker,
        Unit::Agent,
        Unit::EtcdDc,
        Unit::EtcdGlobal,
    ];

    /// The unit's file name.
    #[must_use]
    pub const fn file_name(self) -> &'static str {
        match self {
            Self::Gateway => "sprigdb-gateway.service",
            Self::Controller => "sprigdb-controller.service",
            Self::Worker => "sprigdb-worker.service",
            Self::Agent => "sprigdb-agent.service",
            Self::EtcdDc => "sprigdb-etcd-dc.service",
            Self::EtcdGlobal => "sprigdb-etcd-global.service",
        }
    }
}

/// The configuration file every SprigDB role reads.
pub const CONFIG: &str = "/etc/sprigdb/sprigdb.toml";
/// The binary.
pub const BINARY: &str = "/usr/bin/sprigdb";

fn sprig_role(out: &mut String, desc: &str, role: &str, watchdog: &str, extra: &[&str]) {
    let _ = write!(
        out,
        "[Unit]\n\
         Description=SprigDB {desc}\n\
         Documentation=https://github.com/modlix-india/sprigdb\n\
         After=network-online.target\n\
         Wants=network-online.target\n\
         \n\
         [Service]\n\
         Type=notify\n\
         NotifyAccess=main\n\
         User=sprigdb\n\
         Group=sprigdb\n\
         ExecStart={BINARY} {role} --config {CONFIG}\n\
         WatchdogSec={watchdog}\n\
         Restart=always\n\
         RestartSec=1s\n\
         StateDirectory=sprigdb\n\
         LogsDirectory=sprigdb\n\
         NoNewPrivileges=true\n\
         ProtectSystem=strict\n\
         ProtectHome=true\n\
         PrivateTmp=true\n"
    );
    for l in extra {
        out.push_str(l);
        out.push('\n');
    }
    out.push_str("\n[Install]\nWantedBy=multi-user.target\n");
}

fn etcd(out: &mut String, tier: &str, desc: &str) {
    let _ = write!(
        out,
        "[Unit]\n\
         Description=SprigDB etcd, {desc}\n\
         Documentation=https://etcd.io/docs/\n\
         After=network-online.target\n\
         Wants=network-online.target\n\
         \n\
         [Service]\n\
         Type=notify\n\
         User=etcd\n\
         Group=etcd\n\
         ExecStart=/usr/local/bin/etcd --config-file /etc/sprigdb/etcd-{tier}.yaml\n\
         Restart=always\n\
         RestartSec=5s\n\
         LimitNOFILE=65536\n\
         StateDirectory=sprigdb-etcd-{tier}\n\
         NoNewPrivileges=true\n\
         ProtectSystem=strict\n\
         ProtectHome=true\n\
         \n\
         [Install]\n\
         WantedBy=multi-user.target\n"
    );
}

/// The unit file of `u`.
#[must_use]
pub fn unit(u: Unit) -> String {
    let mut s = String::from("# Generated by SprigDB. Do not edit.\n");
    match u {
        // Draining a gateway waits for sessions (chapter 04): up to a
        // minute before systemd kills it. glibc gives each busy thread a
        // malloc arena of its own and keeps what they free; after the
        // official LDBC run a gateway stayed at 14.2 GB idle with a small
        // live heap (R8 round 10, decision G81), so two arenas.
        Unit::Gateway => sprig_role(
            &mut s,
            "gateway",
            "gateway",
            "10s",
            &[
                "TimeoutStopSec=90s",
                "LimitNOFILE=1048576",
                "AmbientCapabilities=CAP_NET_BIND_SERVICE",
                "Environment=MALLOC_ARENA_MAX=2",
            ],
        ),
        Unit::Controller => sprig_role(
            &mut s,
            "controller",
            "controller",
            "10s",
            &["TimeoutStopSec=30s"],
        ),
        Unit::Worker => sprig_role(&mut s, "worker", "worker", "10s", &["TimeoutStopSec=120s"]),
        // The book's agent unit. It runs as root (it installs packages and
        // manages mariadb.service) and starts before MariaDB, which boots
        // fenced; its own watchdog fences the node when the runtime stalls,
        // and systemd restarts it after WatchdogSec without a ping.
        Unit::Agent => {
            let _ = write!(
                s,
                "[Unit]\n\
                 Description=SprigDB node agent\n\
                 Documentation=https://github.com/modlix-india/sprigdb\n\
                 After=network-online.target\n\
                 Wants=network-online.target\n\
                 Before=mariadb.service\n\
                 \n\
                 [Service]\n\
                 Type=notify\n\
                 NotifyAccess=main\n\
                 ExecStart={BINARY} agent --config {CONFIG}\n\
                 WatchdogSec=3s\n\
                 Restart=always\n\
                 RestartSec=1s\n\
                 StateDirectory=sprigdb-agent\n\
                 \n\
                 [Install]\n\
                 WantedBy=multi-user.target\n"
            );
        }
        Unit::EtcdDc => etcd(&mut s, "dc", "DC tier"),
        Unit::EtcdGlobal => etcd(&mut s, "global", "global voter"),
    }
    s
}

/// Every unit: (file name, contents).
#[must_use]
pub fn units() -> Vec<(&'static str, String)> {
    Unit::ALL
        .iter()
        .map(|u| (u.file_name(), unit(*u)))
        .collect()
}

/// The role MariaDB starts in: `--init-rpl-role`, decided by the agent
/// from the writer lease (or its state file when the DC tier is
/// unreachable).
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum StartRole {
    /// `MASTER`.
    Master,
    /// `SLAVE`.
    Slave,
}

/// Where the drop-ins go.
pub const DROPIN_DIR: &str = "/etc/systemd/system/mariadb.service.d";

/// `10-sprigdb-limits.conf`: the process file limit matches
/// `open_files_limit`, and the service doesn't start at boot on its own
/// (the agent starts it).
#[must_use]
pub fn mariadb_limits_dropin(open_files_limit: u32) -> String {
    format!(
        "# Generated by SprigDB. Do not edit.\n\
         [Unit]\n\
         After=sprigdb-agent.service\n\
         \n\
         [Service]\n\
         LimitNOFILE={open_files_limit}\n\
         Restart=no\n"
    )
}

/// `20-sprigdb-role.conf`: the agent rewrites it before each start.
#[must_use]
pub fn mariadb_role_dropin(role: StartRole) -> String {
    let r = match role {
        StartRole::Master => "MASTER",
        StartRole::Slave => "SLAVE",
    };
    format!(
        "# Written by the SprigDB agent before it starts MariaDB.\n\
         [Service]\n\
         Environment=\"MYSQLD_OPTS=--init-rpl-role={r}\"\n"
    )
}
