//! Embeds Studio's built files.
//!
//! Reads `SPRIG_STUDIO_DIST` (default: `studio/dist` at the workspace root),
//! the output of `pnpm build` in `studio/`, which already holds `.br` and
//! `.gz` siblings of each text file and `studio-manifest.json`. Writes
//! `$OUT_DIR/assets.rs`: one `Asset` per file with `include_bytes!` of the
//! identity, brotli and gzip bytes. Without a build (no `index.html`), or
//! with `SPRIG_STUDIO_DIST=none`, the table is empty and the gateway serves
//! the "not built" page (39932).

use std::fmt::Write as _;
use std::path::{Path, PathBuf};

use sha2::{Digest, Sha256};

fn content_type(path: &str) -> &'static str {
    match path.rsplit('.').next().unwrap_or("") {
        "html" => "text/html; charset=utf-8",
        "js" | "mjs" => "text/javascript; charset=utf-8",
        "css" => "text/css; charset=utf-8",
        "json" | "map" => "application/json",
        "svg" => "image/svg+xml",
        "png" => "image/png",
        "webp" => "image/webp",
        "ico" => "image/x-icon",
        "woff2" => "font/woff2",
        "woff" => "font/woff",
        "ttf" => "font/ttf",
        "wasm" => "application/wasm",
        "txt" => "text/plain; charset=utf-8",
        _ => "application/octet-stream",
    }
}

fn walk(dir: &Path, out: &mut Vec<PathBuf>) {
    let Ok(rd) = std::fs::read_dir(dir) else {
        return;
    };
    for e in rd.flatten() {
        let p = e.path();
        if p.is_dir() {
            walk(&p, out);
        } else {
            out.push(p);
        }
    }
}

fn main() {
    println!("cargo:rerun-if-env-changed=SPRIG_STUDIO_DIST");
    let manifest = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").expect("manifest dir"));
    let dist = match std::env::var("SPRIG_STUDIO_DIST") {
        Ok(v) if v == "none" => None,
        Ok(v) if !v.is_empty() => Some(PathBuf::from(v)),
        _ => Some(manifest.join("../../studio/dist")),
    };
    let out = PathBuf::from(std::env::var("OUT_DIR").expect("out dir")).join("assets.rs");
    let mut code = String::from("// Generated by build.rs.\n");
    let mut version = String::from("none");
    let mut entries = Vec::new();
    if let Some(dist) = dist {
        println!("cargo:rerun-if-changed={}", dist.display());
        if dist.join("index.html").is_file() {
            let mut files = Vec::new();
            walk(&dist, &mut files);
            files.sort();
            for f in files {
                let rel = f
                    .strip_prefix(&dist)
                    .expect("under dist")
                    .to_string_lossy()
                    .replace('\\', "/");
                let ext = Path::new(&rel).extension().and_then(|e| e.to_str());
                if matches!(ext, Some("br" | "gz")) {
                    continue;
                }
                if rel == "studio-manifest.json" {
                    let text = std::fs::read_to_string(&f).unwrap_or_default();
                    if let Some(v) = text
                        .split("\"build_version\"")
                        .nth(1)
                        .and_then(|s| s.split('"').nth(1))
                    {
                        v.clone_into(&mut version);
                    }
                    continue;
                }
                let bytes = std::fs::read(&f).expect("read asset");
                let etag = Sha256::digest(&bytes)
                    .iter()
                    .take(8)
                    .fold(String::new(), |mut s, b| {
                        let _ = write!(s, "{b:02x}");
                        s
                    });
                let inc = |p: &Path| format!("include_bytes!({:?})", p.display().to_string());
                let opt = |ext: &str| {
                    let p = PathBuf::from(format!("{}.{ext}", f.display()));
                    if p.is_file() {
                        format!("Some({})", inc(&p))
                    } else {
                        "None".to_owned()
                    }
                };
                entries.push(format!(
                    "    ({rel:?}, Asset {{ content_type: {ct:?}, identity: {id}, gzip: {gz}, brotli: {br}, etag: \"\\\"{etag}\\\"\", immutable: {imm} }}),\n",
                    ct = content_type(&rel),
                    id = inc(&f),
                    gz = opt("gz"),
                    br = opt("br"),
                    imm = rel.starts_with("assets/"),
                ));
            }
        }
    }
    let _ = writeln!(code, "pub(crate) const BUILD_VERSION: &str = {version:?};");
    code.push_str("pub(crate) static ASSETS: &[(&str, Asset)] = &[\n");
    for e in entries {
        code.push_str(&e);
    }
    code.push_str("];\n");
    std::fs::write(out, code).expect("write assets.rs");
}
